import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from '../web/node_modules/playwright/index.mjs';

const base=process.env.LAB_TEST_URL??'http://127.0.0.1:4321/patrones_dise-o_ia/lab/editor/';
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH||'/usr/bin/google-chrome',args:['--no-sandbox']});
test.after(async()=>{await browser.close()});
test('browser: create, connect, undo/redo, save, reload and open',async()=>{
 const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base);
 await page.locator('#editor-pattern').selectOption('1');
 await page.locator('#editor-add').click();
 await page.locator('#editor-pattern').selectOption('25');
 await page.locator('#editor-add').click();
 assert.equal(await page.locator('#editor-nodes > g').count(),2);
 const ids=await page.locator('#editor-source option').evaluateAll(os=>os.map(o=>o.value));
 await page.locator('#editor-source').selectOption(ids[0]);
 await page.locator('#editor-target').selectOption(ids[1]);
 await page.locator('#editor-connect').click();
 assert.equal(await page.locator('#editor-edges > line').count(),1);
 await page.locator('#editor-remove-edge').click();
 assert.equal(await page.locator('#editor-edges > line').count(),0);
 await page.locator('#editor-undo').click();
 assert.equal(await page.locator('#editor-edges > line').count(),1);
 await page.locator('#editor-redo').click();
 assert.equal(await page.locator('#editor-edges > line').count(),0);
 await page.locator('#project-title').fill('Arquitectura persistida');
 await page.locator('#editor-save').click();
 await page.waitForFunction(() => document.querySelector('#editor-status')?.textContent?.includes('Guardado en este navegador'));
 await page.reload();
 await page.locator('#editor-saved option').filter({hasText:'Arquitectura persistida'}).waitFor({state:'attached'});
 const savedId=await page.locator('#editor-saved option').filter({hasText:'Arquitectura persistida'}).getAttribute('value');
 await page.locator('#editor-saved').selectOption(savedId);
 await page.locator('#editor-load').click();
 await page.waitForFunction(() => document.querySelector('#editor-status')?.textContent?.includes('Proyecto cargado'));
 assert.equal(await page.locator('#editor-nodes > g').count(),2);
 assert.equal(await page.locator('#project-title').inputValue(),'Arquitectura persistida');
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#editor-export').click();
 const download=await downloadPromise;
 const json=JSON.parse(await (await import('node:fs/promises')).readFile(await download.path(),'utf8'));
 assert.equal(json.schemaVersion,1);
 assert.equal(json.nodes.length,2);
 assert.deepEqual(errors,[]);
 await context.close();
});
test('browser: imported invalid HTML-like labels cannot render or replace project',async()=>{
 const context=await browser.newContext();
 const page=await context.newPage();
 await page.goto(base);
 const payload={schemaVersion:1,id:'evil',title:'Prueba',patternIds:[1],nodes:[{id:'a',patternId:1,label:'<img src=x onerror=alert(1)>',position:{x:0,y:0},ports:[]}],edges:[]};
 await page.locator('#editor-import').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(payload))});
 await page.waitForFunction(() => document.querySelector('#editor-status')?.textContent?.startsWith('Error:'));
 assert.equal(await page.locator('#editor-nodes > g').count(),0);
 await context.close();
});
test('browser: keyboard and pointer move pattern nodes',async()=>{
 const context=await browser.newContext({viewport:{width:1440,height:900}});
 const page=await context.newPage();await page.goto(base);
 await page.locator('#editor-pattern').selectOption('1');
 await page.locator('#editor-add').click();
 const node=page.locator('#editor-nodes > g').first();
 const before=await node.getAttribute('transform');
 await node.focus();await page.keyboard.press('ArrowRight');
 const keyboard=await page.locator('#editor-nodes > g').first().getAttribute('transform');
 assert.notEqual(keyboard,before);
 await page.locator('#editor-nodes > g > rect').first().scrollIntoViewIfNeeded();
 const rect=await page.locator('#editor-nodes > g > rect').first().boundingBox();
 assert.ok(rect);
 await page.mouse.move(rect.x+50,rect.y+20);
 await page.mouse.down();await page.mouse.move(rect.x+90,rect.y+55,{steps:4});await page.mouse.up();
 const moved=await page.locator('#editor-nodes > g').first().getAttribute('transform');
 assert.notEqual(moved,keyboard);
 await context.close();
});

